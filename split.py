"""Seed-grouped train/test split over S-CECILIA gold.

S-CECILIA was generated by an LLM from 57 seed incidents (Seed_ID in
S-CECILIA.csv). Reports from one seed share a template, so a random
report-level split leaks: every test seed also appears in training. Here
whole seeds are held out.

  test           gold reports whose seed is in the held-out seeds (~25%)
  train          the other gold reports
  gold_seed      seed incident of every gold report
"""
import collections, json, random
from pathlib import Path
import pandas as pd
import gold

HERE = Path(__file__).resolve().parent
TEST_SHARE = 0.25


def build():
    recs = pd.read_csv(HERE / "data" / "S-CECILIA.csv")
    seed_of = dict(zip(recs.Record_ID, recs.Seed_ID))
    g = gold.load()
    gcsv = pd.read_csv(HERE / "data" / "S-CECILIA-NER-GOLD.csv").set_index("Gold_ID")
    gseed = {x["id"]: seed_of[gcsv.at[x["id"], "Record_ID"]] for x in g}

    per_seed = collections.Counter(gseed.values())
    seeds = sorted(per_seed); random.seed(42); random.shuffle(seeds)
    test_seeds, n = [], 0
    for s in seeds:
        if n >= TEST_SHARE * len(g): break
        test_seeds.append(s); n += per_seed[s]
    test = [x["id"] for x in g if gseed[x["id"]] in test_seeds]
    train = [x["id"] for x in g if gseed[x["id"]] not in test_seeds]
    return dict(test_seeds=sorted(test_seeds), test=test, train=train, gold_seed=gseed)


if __name__ == "__main__":
    out = build()
    json.dump(out, open(HERE / "split.json", "w"), indent=1)
    print(f"test seeds {len(out['test_seeds'])} | gold test {len(out['test'])} | gold train {len(out['train'])}")
